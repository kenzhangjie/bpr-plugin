"""Build /Users/ken/Documents/Transcript/index.html from all BPR HTML files.

Scans the directory for files matching `<YYYY-MM-DD>_<source>_<...>.html`,
extracts each file's <h1>, .hero-zh, .hero-eyebrow, and renders a single-page
landing/library at index.html. Designed for bpr.ken.solar.

Usage:
  /usr/bin/python3 ~/.claude/skills/bpr-skill/scripts/build_index.py

Idempotent: just rerun whenever new BPR files land in the dir.
"""
from __future__ import annotations

import re
import sys
from datetime import date as _date
from html import escape
from pathlib import Path

TRANSCRIPT_DIR = Path("/Users/ken/Documents/Transcript")
INDEX_PATH = TRANSCRIPT_DIR / "index.html"

FILENAME_RE = re.compile(r"^(\d{4}-\d{2}-\d{2})_([^_]+)_(.+)\.html$")
TAG_STRIP_RE = re.compile(r"<[^>]+>")
WS_RE = re.compile(r"\s+")


def clean(text: str) -> str:
    text = TAG_STRIP_RE.sub("", text)
    text = WS_RE.sub(" ", text)
    return text.strip()


def extract_h1_with_em(html: str) -> str:
    """Extract <h1> content, preserving <em> tags for emphasis styling."""
    m = re.search(r"<h1[^>]*>(.+?)</h1>", html, re.DOTALL)
    if not m:
        return ""
    inner = m.group(1)
    # Keep <em>...</em> markers; strip everything else
    inner = re.sub(r"<(?!/?em\b)[^>]+>", "", inner, flags=re.IGNORECASE)
    return WS_RE.sub(" ", inner).strip()


def extract_field(html: str, css_class: str) -> str:
    pattern = (
        rf'class="[^"]*\b{re.escape(css_class)}\b[^"]*"[^>]*>(.+?)</'
        r"(?:p|div|h[1-6]|span|section|header|footer|article)>"
    )
    m = re.search(pattern, html, re.DOTALL)
    return clean(m.group(1)) if m else ""


def parse_entry(path: Path) -> dict | None:
    m = FILENAME_RE.match(path.name)
    if not m:
        return None
    iso, source, rest = m.groups()
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except Exception:
        return None
    # check for matching poster PNG (only generated by /bpr all)
    stem = path.stem  # filename without .html
    poster = TRANSCRIPT_DIR / f"{stem}-poster.png"
    poster_href = f"{stem}-poster.png" if poster.exists() else None
    return {
        "iso": iso,
        "year": iso[:4],
        "source": source,
        "rest": rest,
        "href": path.name,
        "poster_href": poster_href,
        "h1": extract_h1_with_em(text) or rest.replace("-", " ").title(),
        "zh": extract_field(text, "hero-zh"),
        "eyebrow": extract_field(text, "hero-eyebrow"),
    }


def collect_entries() -> list[dict]:
    entries: list[dict] = []
    for f in TRANSCRIPT_DIR.glob("*.html"):
        if f.name == "index.html":
            continue
        if f.name.endswith("-poster.html"):
            continue
        e = parse_entry(f)
        if e:
            entries.append(e)
    entries.sort(key=lambda x: x["iso"], reverse=True)
    return entries


def render_entry_li(e: dict) -> str:
    iso = e["iso"]
    pretty_date = f'{iso[:4]} · {iso[5:7]} · {iso[8:10]}'
    h1_html = e["h1"]
    zh = escape(e["zh"]) if e["zh"] else ""
    eyebrow = escape(e["eyebrow"]) if e["eyebrow"] else ""
    href = escape(e["href"])
    source_tag = escape(e["source"])
    has_poster = bool(e.get("poster_href"))
    poster_href = escape(e["poster_href"]) if has_poster else ""
    cls = "entry has-poster" if has_poster else "entry"

    poster_block = ""
    if has_poster:
        poster_block = f"""
  <a class="entry-poster" href="{poster_href}" target="_blank" rel="noopener" aria-label="海报 PNG">
    <img src="{poster_href}" loading="lazy" alt="">
    <span class="entry-poster-badge">📷</span>
  </a>"""

    return f"""<li class="{cls}">
  <div class="entry-date">{pretty_date}</div>
  <div class="entry-body">
    <div class="entry-source">{source_tag}</div>
    <a class="entry-h1-link" href="{href}"><h3 class="entry-h1">{h1_html}</h3></a>
    {f'<div class="entry-zh">{zh}</div>' if zh else ''}
    {f'<div class="entry-eyebrow">{eyebrow}</div>' if eyebrow else ''}
  </div>{poster_block}
</li>"""


