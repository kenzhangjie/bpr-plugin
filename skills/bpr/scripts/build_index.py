def main() -> int:
    entries = collect_entries()
    if not entries:
        print("No BPR entries found.", file=sys.stderr)
        return 1
    html = render_index(entries)

    # L5 hard rule: macOS FS is case-insensitive but case-preserving.
    # If a stale INDEX.html (uppercase) exists, plain write_text("index.html")
    # silently overwrites it but keeps the uppercase filename, and Vercel
    # serves only lowercase index.html as root → bpr.ken.solar 404.
    # Solve: explicitly unlink any existing match first, then write fresh.
    for cand in ("index.html", "INDEX.html", "Index.html"):
        p = TRANSCRIPT_DIR / cand
        if p.exists():
            p.unlink()
    INDEX_PATH.write_text(html, encoding="utf-8")
    print(f"✓ wrote {INDEX_PATH} ({len(html):,} chars, {len(entries)} entries)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
